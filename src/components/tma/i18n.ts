export const translations: Record<Language, Translations> = { en, ru, uz, by };

export function getDefaultLanguage(): Language {
  try {
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    const langCode = (window as any)?.Telegram?.WebApp?.initDataUnsafe?.user?.language_code ?? "";
    if (langCode === "ru") return "ru";
    if (langCode === "uz") return "uz";
    if (langCode === "be" || langCode === "by") return "by";
    return "en";
  } catch {
    return "en";
  }
}
